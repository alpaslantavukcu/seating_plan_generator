// Plan templates: a portable, settings-only description of a setup — exam name,
// classrooms and their fill order, custom capacities, seed, seat-cell fields.
// Templates deliberately carry NO student data and NO generated plan.
//
// Two shapes, on purpose:
//   * the .json file — readable, carries everything including the exam name;
//   * the code / link — a packed binary payload that carries everything EXCEPT
//     the exam name, because the name is the bulk of the bytes and a template
//     exists to be reused under a different exam anyway.
//
// Pure module: no DOM, no i18n. Warnings come back as {key, params} for the
// caller to translate.

import { DEFAULT_CELL_FIELDS } from './store.js';

export const TEMPLATE_TYPE = 'seating-plan-template';
export const TEMPLATE_VERSION = 1;

const CODE_PREFIX = 'SP1-';
const CODE_FORMAT = 1;
const MAX_NAME_LENGTH = 200;

// APPEND ONLY — NEVER REORDER OR REMOVE.
// A room's position here is its one-byte id inside every code ever shared, so
// reordering would silently decode old codes into the wrong classrooms. This is
// deliberately a frozen list rather than Object.keys(classrooms.rooms): that
// file is regenerated by tools/convert_templates.py whenever a template changes.
// A room missing from this list still works — it falls back to the inline-name
// escape below and just costs a few more characters.
const ROOM_TABLE = [
  '101', '102', '104', '121', '122', '123',
  'Z-16', 'Z-17', 'Z-18', 'Z-19', 'Z-20', 'Z-21', 'Z-22', 'Z-23',
  'MED_A31', 'MED_A32', 'EEB_5204', 'EEB_5302',
];

const FLAG_CUSTOM_CAPS = 1;
const FLAG_FIELD_ID = 2;
const FLAG_FIELD_NAME = 4;
const FLAG_FIELD_SEAT = 8;
const FLAG_SEED = 16;

const NAME_ESCAPE = 0x80; // set on a room byte: an inline UTF-8 name follows

export function extractSettings(state) {
  return {
    examName: state.examName,
    selectedRooms: state.selectedRooms.slice(),
    useCustomCapacities: state.useCustomCapacities,
    customCapacities: { ...state.customCapacities },
    seed: state.seed,
    cellFields: { ...state.cellFields },
  };
}

export function buildTemplate(settings, classroomsVersion) {
  return {
    type: TEMPLATE_TYPE,
    version: TEMPLATE_VERSION,
    savedAt: new Date().toISOString(),
    classroomsVersion: classroomsVersion ?? null,
    settings,
  };
}

export function serializeTemplate(template) {
  return JSON.stringify(template, null, 2);
}

export function parseTemplateJson(text) {
  return JSON.parse(text);
}

/* ---------- byte plumbing ---------- */

function bytesToBase64Url(bytes) {
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function base64UrlToBytes(code) {
  const base64 = code.replace(/-/g, '+').replace(/_/g, '/');
  const padded = base64.padEnd(Math.ceil(base64.length / 4) * 4, '=');
  return Uint8Array.from(atob(padded), (ch) => ch.charCodeAt(0));
}

function pushVarint(out, value) {
  let n = value >>> 0;
  while (n >= 0x80) {
    out.push((n & 0x7f) | 0x80);
    n >>>= 7;
  }
  out.push(n);
}

function readVarint(bytes, cursor) {
  let result = 0;
  let shift = 0;
  let byte;
  do {
    if (cursor.i >= bytes.length) throw new Error('truncated code');
    byte = bytes[cursor.i++];
    result |= (byte & 0x7f) << shift;
    shift += 7;
  } while (byte & 0x80);
  return result >>> 0;
}

function checksum(bytes) {
  let sum = 0;
  for (const byte of bytes) sum = (sum * 31 + byte) & 0xff;
  return sum;
}

function digitsOnly(seed) {
  return typeof seed === 'string' || typeof seed === 'number'
    ? String(seed).trim().replace(/\D/g, '')
    : '';
}

/* ---------- code / link encoding ---------- */

// Packs everything but the exam name. Deterministic: the same settings always
// produce the same code, and any difference — including room order, which is
// fill order — produces a different one.
export function encodeSettings(settings) {
  const rooms = Array.isArray(settings.selectedRooms) ? settings.selectedRooms : [];
  if (rooms.length > 255) throw new Error('too many classrooms to encode');

  const fields = settings.cellFields || DEFAULT_CELL_FIELDS;
  const seed = digitsOnly(settings.seed);
  const useCustomCapacities = !!settings.useCustomCapacities;

  const out = [CODE_FORMAT];
  out.push(
    (useCustomCapacities ? FLAG_CUSTOM_CAPS : 0)
    | (fields.id ? FLAG_FIELD_ID : 0)
    | (fields.name ? FLAG_FIELD_NAME : 0)
    | (fields.seat ? FLAG_FIELD_SEAT : 0)
    | (seed ? FLAG_SEED : 0),
  );

  out.push(rooms.length);
  for (const id of rooms) {
    const index = ROOM_TABLE.indexOf(id);
    if (index >= 0) {
      out.push(index);
    } else {
      const name = new TextEncoder().encode(String(id));
      if (name.length > 0x7f) throw new Error('classroom name too long to encode');
      out.push(NAME_ESCAPE | name.length);
      for (const byte of name) out.push(byte);
    }
  }

  if (useCustomCapacities) {
    const caps = settings.customCapacities || {};
    for (const id of rooms) {
      // 0 means "no override for this room".
      pushVarint(out, Math.max(0, Math.trunc(Number(caps[id])) || 0));
    }
  }

  if (seed) pushVarint(out, Number(seed) >>> 0);

  out.push(checksum(out));
  return CODE_PREFIX + bytesToBase64Url(Uint8Array.from(out));
}

// Accepts a bare code, a prefixed one, or either with stray whitespace from a
// chat or email client. Returns {settings, warnings} with NO examName key, so
// applying it leaves whatever the user already typed alone.
export function decodeSettings(code, rooms) {
  const cleaned = String(code ?? '').trim().replace(/\s+/g, '');
  const body = cleaned.startsWith(CODE_PREFIX) ? cleaned.slice(CODE_PREFIX.length) : cleaned;
  if (!body) throw new Error('empty template code');

  const bytes = base64UrlToBytes(body);
  if (bytes.length < 4) throw new Error('code too short');
  if (checksum(bytes.subarray(0, bytes.length - 1)) !== bytes[bytes.length - 1]) {
    throw new Error('code is damaged (checksum mismatch)');
  }

  const cursor = { i: 0 };
  const end = bytes.length - 1; // the checksum byte is not payload
  const readByte = () => {
    if (cursor.i >= end) throw new Error('truncated code');
    return bytes[cursor.i++];
  };

  if (readByte() !== CODE_FORMAT) throw new Error('unsupported code format');
  const flags = readByte();
  const roomCount = readByte();

  const selectedRooms = [];
  for (let n = 0; n < roomCount; n++) {
    const marker = readByte();
    if (marker & NAME_ESCAPE) {
      const length = marker & 0x7f;
      if (cursor.i + length > end) throw new Error('truncated code');
      selectedRooms.push(new TextDecoder().decode(bytes.subarray(cursor.i, cursor.i + length)));
      cursor.i += length;
    } else {
      // Out of range means the code came from a build with more rooms; keep the
      // rest of the template usable and let normalizeSettings drop this one.
      selectedRooms.push(ROOM_TABLE[marker] ?? `#${marker}`);
    }
  }

  const useCustomCapacities = !!(flags & FLAG_CUSTOM_CAPS);
  const customCapacities = {};
  if (useCustomCapacities) {
    for (const id of selectedRooms) {
      const capacity = readVarint(bytes, cursor);
      if (cursor.i > end) throw new Error('truncated code');
      if (capacity > 0) customCapacities[id] = capacity;
    }
  }

  let seed = '';
  if (flags & FLAG_SEED) {
    seed = String(readVarint(bytes, cursor));
    if (cursor.i > end) throw new Error('truncated code');
  }

  if (cursor.i !== end) throw new Error('trailing bytes in code');

  return normalizeSettings({
    selectedRooms,
    useCustomCapacities,
    customCapacities,
    seed,
    cellFields: {
      id: !!(flags & FLAG_FIELD_ID),
      name: !!(flags & FLAG_FIELD_NAME),
      seat: !!(flags & FLAG_FIELD_SEAT),
    },
  }, rooms);
}

/* ---------- validation ---------- */

// Templates move between machines whose docs/data/classrooms.json may differ, so
// nothing in one is trusted: unknown rooms are dropped, capacities are clamped
// to what the room actually holds, and the caller is told what changed.
//
// examName is only produced when the source has the key. A code omits it, and a
// settings patch without the key leaves the exam name in the form untouched.
function normalizeSettings(src, rooms) {
  const warnings = [];
  const settings = {};

  if ('examName' in src) {
    settings.examName = typeof src.examName === 'string'
      ? src.examName.trim().slice(0, MAX_NAME_LENGTH)
      : '';
  }

  // Order is fill order — preserve it, drop duplicates and unknown rooms.
  const seen = new Set();
  const selectedRooms = [];
  const dropped = [];
  for (const id of Array.isArray(src.selectedRooms) ? src.selectedRooms : []) {
    if (typeof id !== 'string' || seen.has(id)) continue;
    seen.add(id);
    if (rooms[id]) selectedRooms.push(id);
    else dropped.push(id);
  }
  if (dropped.length) {
    warnings.push({ key: 'tplRoomsDropped', params: { rooms: dropped.join(', ') } });
  }
  settings.selectedRooms = selectedRooms;

  const rawCaps = src.customCapacities && typeof src.customCapacities === 'object'
    ? src.customCapacities
    : {};
  const customCapacities = {};
  let clamped = 0;
  for (const id of selectedRooms) {
    const wanted = Math.trunc(Number(rawCaps[id]));
    if (!Number.isFinite(wanted) || wanted <= 0) continue;
    const capacity = Math.min(wanted, rooms[id].capacity);
    if (capacity !== wanted) clamped++;
    customCapacities[id] = capacity;
  }
  if (clamped) warnings.push({ key: 'tplCapsClamped', params: { n: clamped } });
  settings.customCapacities = customCapacities;
  settings.useCustomCapacities = !!src.useCustomCapacities;

  settings.seed = digitsOnly(src.seed);

  const rawFields = src.cellFields && typeof src.cellFields === 'object' ? src.cellFields : {};
  const cellFields = { id: !!rawFields.id, name: !!rawFields.name, seat: !!rawFields.seat };
  // All-false would make the plan unbuildable (see validate() in main.js).
  settings.cellFields = cellFields.id || cellFields.name || cellFields.seat
    ? cellFields
    : { ...DEFAULT_CELL_FIELDS };

  return { settings, warnings };
}

// The .json file / stored session path: checks the wrapper, then the fields.
// Throws if the document is not a template at all.
export function validateTemplate(raw, rooms) {
  if (!raw || typeof raw !== 'object') throw new Error('not a template');
  if (raw.type !== TEMPLATE_TYPE) throw new Error('not a seating plan template');
  if (raw.version !== TEMPLATE_VERSION) throw new Error(`unsupported template version: ${raw.version}`);

  const src = raw.settings;
  if (!src || typeof src !== 'object') throw new Error('template has no settings');

  return normalizeSettings({ examName: '', ...src }, rooms);
}
